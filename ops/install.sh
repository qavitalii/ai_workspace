#!/usr/bin/env bash
set -Eeuo pipefail
cd "$(dirname "$0")/.."
mode="${1:---server}"
if [[ "$mode" != '--local' && "$mode" != '--server' ]]; then echo 'Usage: ./ops/install.sh [--local|--server]'; exit 1; fi
if [[ "$(pwd)" =~ [[:space:]] ]]; then echo 'Install into a path without spaces.'; exit 1; fi
if [[ "$mode" == '--server' && "$(uname)" == Linux && "$EUID" == 0 ]]; then
  if ! command -v python3 >/dev/null || ! command -v cron >/dev/null || ! command -v openssl >/dev/null; then
    apt-get update && apt-get install -y python3 cron openssl ca-certificates curl
  fi
  systemctl enable --now cron
fi
if ! command -v docker >/dev/null; then
  if [[ "$mode" == '--server' && "$(uname)" == Linux && "$EUID" == 0 ]]; then
    echo 'Installing Docker from the official Docker installer…'
    apt-get update && apt-get install -y ca-certificates curl openssl
    installer=$(mktemp); curl --fail --show-error --silent --location https://get.docker.com -o "$installer"; sh "$installer"; rm -f "$installer"
  else echo 'Install and start Docker Desktop, then run this command again: https://www.docker.com/products/docker-desktop/'; exit 1; fi
fi
docker info >/dev/null || { echo 'Start Docker (or run this installer with sudo on Linux).'; exit 1; }
docker compose version >/dev/null
command -v openssl >/dev/null || { echo 'Install openssl first.'; exit 1; }
command -v python3 >/dev/null || { echo 'Install Python 3 (used by backup restoration) first.'; exit 1; }
compose=(docker compose)
[[ "$mode" == '--local' ]] && compose+=(-f compose.yaml -f compose.local.yaml)
if [[ ! -f .env ]]; then
  umask 077
  caddy_config=Caddyfile; tls_server_name=localhost; bind_address=0.0.0.0
  if [[ "$mode" == '--local' ]]; then origin='http://localhost:8080'; address=':80'; environment=development
  else
    read -rp 'Domain or public IP assigned to this server (without https://): ' server_host
    server_settings=$(python3 ops/server-address.py "$server_host")
    read -r tls_server_name address caddy_config <<< "$server_settings"
    [[ "$address" == \[* ]] && bind_address='[::]'
    origin="https://$address"; environment=production
    if [[ "$caddy_config" == Caddyfile.ip ]]; then
      echo "HTTPS will use Let's Encrypt IP certificates with automatic renewal. Keep ports 80 and 443 reachable."
    fi
  fi
  cat > .env <<ENV
POSTGRES_PASSWORD=$(openssl rand -hex 24)
ENCRYPTION_KEY=$(openssl rand -hex 32)
DATA_ROOT=$(pwd)/.data
APP_ORIGIN=$origin
SITE_ADDRESS=$address
CADDY_CONFIG=$caddy_config
TLS_SERVER_NAME=$tls_server_name
HTTP_BIND=$bind_address
HTTPS_BIND=$bind_address
NODE_ENV=$environment
MAX_CONCURRENT=3
MAX_FILE_MB=25
MAX_ATTACHMENTS=10
ENABLE_AUTO_HANDOFF=false
VAPID_SUBJECT=mailto:owner@example.com
ENV
  echo "$mode" > .install-mode
fi
[[ -f .install-mode && "$(cat .install-mode)" != "$mode" ]] && { echo 'This checkout is configured for a different mode. See docs/deployment.md to migrate it.'; exit 1; }
# .env is generated by this script and contains no shell fragments.
set -a; source .env; set +a
mkdir -p "$DATA_ROOT"; chmod 700 "$DATA_ROOT"
"${compose[@]}" build server runner-image
if ! grep -q '^VAPID_PUBLIC_KEY=' .env; then
  "${compose[@]}" run --rm --no-deps server node --input-type=module -e 'import webpush from "web-push";const k=webpush.generateVAPIDKeys();console.log("VAPID_PUBLIC_KEY="+k.publicKey+"\nVAPID_PRIVATE_KEY="+k.privateKey)' >> .env
  set -a; source .env; set +a
fi
"${compose[@]}" up -d --wait db
exists=$("${compose[@]}" exec -T db psql -U workspace -d workspace -Atc "SELECT EXISTS(SELECT 1 FROM information_schema.tables WHERE table_name='owner')")
owner_count=0
if [[ "$exists" == t ]]; then owner_count=$("${compose[@]}" exec -T db psql -U workspace -d workspace -Atc 'SELECT count(*) FROM owner'); fi
if [[ "$owner_count" == 0 ]]; then
  read -rsp 'Owner password (at least 14 characters): ' OWNER_PASSWORD; echo
  read -rsp 'Repeat password: ' repeat; echo
  [[ "$OWNER_PASSWORD" == "$repeat" && ${#OWNER_PASSWORD} -ge 14 ]] || { echo 'Passwords must match and contain at least 14 characters.'; exit 1; }
  export OWNER_PASSWORD
  "${compose[@]}" run --rm -e OWNER_PASSWORD server node dist/node/server/setup.js
  unset OWNER_PASSWORD repeat
  echo 'Save the QR code in your authenticator before continuing.'
  read -rp 'Press Enter when ready… ' _
fi
"${compose[@]}" up -d --wait server caddy
if [[ "$mode" == '--server' && "$EUID" == 0 ]]; then
  [[ -f .backup-key ]] || (umask 077; openssl rand -hex 32 > .backup-key)
  printf '17 3 * * * root cd %s && ./ops/backup.sh >> /var/log/ai-workspace-backup.log 2>&1\n' "$(pwd)" > /etc/cron.d/ai-workspace-backup
  echo 'Daily encrypted backups enabled at 03:17 server time. Copy .backup-key to a separate safe location.'
fi
printf '\nWorkspace services started: %s\n' "$APP_ORIGIN"
if [[ "$mode" == '--server' ]]; then
  echo 'HTTPS certificate issuance can take a few minutes. If the address does not open, check: ./ops/compose.sh logs --tail=100 caddy'
fi
echo 'Next: sign in, connect GitHub, add agent accounts, create a chat.'
